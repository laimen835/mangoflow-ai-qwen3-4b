def norm(text):return re.sub(r'\s+',' ',text).strip().casefold().replace('ё','е')


def main():
    corpus=json.loads(Path('work/search-corpus.json').read_text(encoding='utf-8'))
    cases=[]
    for family,(name,url,anchor,questions) in enumerate(FACTS):
        evidence=[c for c in corpus if c['url']==url and norm(anchor) in norm(c['text'])]
        assert evidence, (name,anchor)
        for variant,question in enumerate(questions[:3]):
            extra=questions[3] if len(questions)>3 and variant==2 else {}
            split='tune' if variant==0 or (variant==2 and family%2==0) else 'holdout'
            cases.append({'id':len(cases)+1,'family':name,'split':split,'question':question,'answerable':True,
                          'evidence':[{'chunk_id':c['id'],'url':c['url'],'quote':re.sub(r'\s+',' ',c['text']).strip()}for c in evidence],**extra})
    for i,(question,reason) in enumerate(NEGATIVE):
        cases.append({'id':len(cases)+1,'family':reason,'split':'tune' if i%2==0 else 'holdout',
                      'question':question,'answerable':False,'evidence':[]})
    assert len(cases)==80 and sum(c['answerable'] for c in cases)==60
    assert sum(c['split']=='tune' for c in cases)==40
    corpus_hash=hashlib.sha256(json.dumps([(c['id'],c['text']) for c in corpus],ensure_ascii=False).encode()).hexdigest()
    path=Path('tests/eval/search_cases.json');path.parent.mkdir(exist_ok=True)
    path.write_text(json.dumps({'version':1,'corpus_sha256':corpus_hash,'cases':cases},ensure_ascii=False,indent=2),encoding='utf-8')
    print('Frozen: 80 questions, 60 evidenced / 20 insufficient, tune=40 / holdout=40')


if __name__=='__main__':main()
